def calculate_fuel_efficiency(distance, fuel_consumed, unit_distance='miles', unit_fuel='gallons'):
    """Calculates fuel efficiency (e.g., MPG, km/L).

    Args:
        distance (float): The distance traveled.
        fuel_consumed (float): The amount of fuel consumed.
        unit_distance (str): The unit of distance ('miles' or 'kilometers').
        unit_fuel (str): The unit of fuel ('gallons' or 'liters').

    Returns:
        float: The calculated fuel efficiency.
        str: The unit of fuel efficiency (e.g., 'MPG', 'km/L').
    """
    if fuel_consumed <= 0:
        return 0, 'N/A' # Avoid division by zero

    efficiency = distance / fuel_consumed
    unit_efficiency = f"{unit_distance.capitalize()}/{unit_fuel.capitalize()}"
    return efficiency, unit_efficiency

